#include "../../include/minishell.h"

int	ms_isdigit(char *str)
{
	if (!str || !*str)
		return (1);
	while (*str && ((*str >= '0' && *str <= '9') || (*str == '-') || (*str == '+')))
		str++;
	if (!*str)
		return (1);
	return (0);
}
