#include "../../include/minishell.h"

int	ms_isalpha(char *str)
{
	if (!str || !*str)
		return (1);
	while (*str && ((*str >= 65 && *str <= 90) || (*str >= 97 && *str <= 122)))
		str++;
	if (!*str)
		return (1);
	return (0);
}
